
void main(List<String> arguments) {
  // Numbers: int
  int score = 23;
  var count = 23;
  int hexValue = 0xEADEBAEE;

  // Numbers: double
  double percentage = 93.4;
  var percent = 82.533;
  double exponents = 1.42e5;

  // Strings
  String name = "Henry";
  var company = "Google";

  // Boolean
  bool isValid = true;
  var isAlive = false;

  // Print all values
  print(score);
  print(count);
  print(hexValue);
  print(percentage);
  print(percent);
  print(exponents);
  print(name);
  print(company);
  print(isValid);
  print(isAlive);

  // NOTE: All data types in Dart are Objects.
  // In Dart with null safety, non-nullable types must be initialized
}